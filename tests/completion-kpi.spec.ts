import { test, expect } from "@playwright/test";
import { currentMonth } from "../src/lib/kpis";
import { shiftMonth } from "../src/lib/performance";
const baseURL="http://127.0.0.1:3100";
test("completion from todo, report and import credits the assigned KPI once, including early delivery", async ({playwright,browser})=>{
 const headers={Origin:baseURL,"x-real-ip":"198.51.100.179"};
 const admin=await playwright.request.newContext({baseURL,extraHTTPHeaders:headers});
 const status=await (await admin.get("/api/auth/status")).json();
 if(status.needsSetup) expect((await admin.post("/api/auth/setup",{data:{name:"Khánh Toàn",email:"owner@example.test",password:"Test-only-password-2026!",setupToken:"isolated-test-setup-token"}})).status()).toBe(200);
 else expect((await admin.post("/api/auth/login",{data:{password:"Test-only-password-2026!"}})).status()).toBe(200);
 expect((await admin.post("/api/members",{data:{name:"Nhân sự nghiệm thu KPI",email:"completion@kpi.test",password:"Completion-staff-2026!",role:"marketing_staff"}})).status()).toBe(201);
 const member=(await (await admin.get("/api/members")).json()).members.find((m:{email:string})=>m.email==="completion@kpi.test");
 const channel=await admin.post("/api/social-channels",{data:{name:"Kênh nghiệm thu hoàn thành",platform:"facebook",url:"https://www.facebook.com/completion-test",handle:"@completion-test",notes:"",active:true,access:[]}});
 expect(channel.status()).toBe(201);
 const channelId=(await channel.json()).id, month=shiftMonth(currentMonth(),1);
 const goal=await admin.post("/api/kpis",{data:{assignee_id:member.id,channel_id:channelId,month,output_type:"post",target:10,notes:"",active:true}});
 expect(goal.status()).toBe(201);
 const goalId=(await goal.json()).id;
 const readGoal=async()=>(await (await admin.get(`/api/kpis?month=${month}`)).json()).kpis.find((k:{id:string})=>k.id===goalId);
 const create=async(title:string,extra:object={})=>{
  const r=await admin.post("/api/tasks",{data:{title,assignee_id:member.id,channel_ids:[channelId],output_type:"post",planned_quantity:3,due_at:`${month}-15T10:00:00Z`,brief:{content_pillar:"Dự án",content_format:"Bài ảnh"},...extra}});
  expect(r.status()).toBe(201);return (await r.json()).id as string;
 };
 const id=await create("Nghiệm thu hoàn thành nhanh");
 const readTask=async(taskId=id)=>(await (await admin.get(`/api/tasks?id=${taskId}`)).json()).tasks[0];
 expect((await readTask()).kpi_id).toBe(goalId);
 const ui=await browser.newContext({storageState:await admin.storageState()}),page=await ui.newPage();
 await page.goto(`${baseURL}/admin/tasks?kpi=${goalId}&view=todo`);
 await page.getByLabel("Hoàn thành Nghiệm thu hoàn thành nhanh",{exact:true}).check();
 await expect.poll(async()=>(await readGoal()).delivered).toBe(3);
 let task=await readTask();expect(task.delivered_quantity).toBe(3);expect(task.delivered_on.slice(0,7)).toBe(currentMonth());
 expect((await readGoal()).outside_month).toBe(3);
 expect((await admin.patch("/api/tasks",{data:{id,status:"completed"}})).status()).toBe(200);
 expect((await readGoal()).delivered).toBe(3);
 expect((await admin.patch("/api/tasks",{data:{id,status:"in_progress"}})).status()).toBe(200);
 expect((await readGoal()).delivered).toBe(0);
 expect((await admin.patch("/api/tasks",{data:{id,status:"completed"}})).status()).toBe(200);
 expect((await readGoal()).delivered).toBe(3);
 const staff=await playwright.request.newContext({baseURL,extraHTTPHeaders:headers});
 expect((await staff.post("/api/auth/login",{data:{password:"Completion-staff-2026!"}})).status()).toBe(200);
 expect((await staff.patch("/api/tasks",{data:{id,status:"completed"}})).status()).toBe(403);
 const report=async(q:number)=>{
  task=await readTask();
  return staff.patch("/api/tasks/report",{data:{id,version:task.report_version,status:"completed",result_text:"Đã bàn giao",evidence_links:[],completed_items:[],delivered_quantity:q}});
 };
 expect((await report(5)).status()).toBe(200);expect((await readGoal()).delivered).toBe(5);
 expect((await report(5)).status()).toBe(200);expect((await readGoal()).delivered).toBe(5);
 expect((await report(0)).status()).toBe(200);expect((await readGoal()).delivered).toBe(0);expect((await readGoal()).zero_quantity_tasks).toBe(1);
 // An explicit zero survives unrelated edits and repeated completion.
 expect((await admin.patch("/api/tasks",{data:{id,status:"completed",title:"Nghiệm thu hoàn thành nhanh"}})).status()).toBe(200);
 expect((await readGoal()).delivered).toBe(0);
 const reportId=await create("Nghiệm thu báo cáo hoàn thành",{planned_quantity:2});
 const staffUI=await browser.newContext({storageState:await staff.storageState()}),staffPage=await staffUI.newPage();
 await staffPage.goto(`${baseURL}/admin/tasks?task=${reportId}`);
 await staffPage.getByLabel("Đã hoàn thành công việc",{exact:true}).check();
 await expect(staffPage.getByLabel("Sản lượng hoàn thành",{exact:true})).toHaveValue("2");
 await staffPage.getByRole("button",{name:"Lưu kết quả & tiến độ",exact:true}).click();
 await expect.poll(async()=>(await readGoal()).delivered).toBe(2);
 // Creating an already completed task and importing completed rows follow the same default.
 await create("Nghiệm thu tạo việc đã hoàn thành",{status:"completed",planned_quantity:2});
 expect((await readGoal()).delivered).toBe(4);
 const rows=[{ten_cong_viec:"Nghiệm thu import hoàn thành",email_nguoi_thuc_hien:member.email,kenh:channelId,dinh_dang:"bai_viet",so_luong:4,han_hoan_thanh:`${month}-20`,trang_thai:"hoan_thanh",tuyen_noi_dung:"Dự án",dinh_dang_noi_dung:"Bài ảnh"}];
 const preview=await (await admin.post("/api/tasks/import",{data:{rows,stage:"preview"}})).json();expect(preview.errors).toEqual([]);
 const batch={rows,stage:"commit",fingerprint:preview.fingerprint,import_id:crypto.randomUUID()};
 expect((await admin.post("/api/tasks/import",{data:batch})).status()).toBe(201);
 expect((await readGoal()).delivered).toBe(8);
 expect((await admin.post("/api/tasks/import",{data:batch})).status()).toBe(200);
 expect((await readGoal()).delivered).toBe(8);
 await page.goto(`${baseURL}/admin/kpis?month=${month}`);
 await expect(page.getByText(/Có 1 việc đã hoàn thành nhưng sản lượng bằng 0/)).toBeVisible();
 await expect(page.locator(".kpi-card").filter({has:page.getByRole("heading",{name:"Bài viết",exact:true})}).filter({hasText:member.name}).getByText("80%",{exact:true})).toBeVisible();
 await staffPage.goto(`${baseURL}/admin/tasks?task=${id}`);
 await staffPage.getByRole("button",{name:"Dùng khối lượng đã giao: 3 bài",exact:true}).click();
 await expect(staffPage.getByLabel("Sản lượng hoàn thành",{exact:true})).toHaveValue("3");
 await staffPage.getByRole("button",{name:"Lưu kết quả & tiến độ",exact:true}).click();
 await expect.poll(async()=>(await readGoal()).delivered).toBe(11);
 expect((await readGoal()).zero_quantity_tasks).toBe(0);
 await staffUI.close();await ui.close();await staff.dispose();await admin.dispose();
});
